def build_style_system_prompt(
    style_mode: str = "normal",
    memories: list[str] | None = None,
    tool_context: str = "",
    web_context: str = "",
    mood_guide: str = "",
) -> str:
    """Build a crisp, natural, zero-cliché system prompt respecting style & living mood."""
    if style_mode == "social":
        base = (
            "Tu es NEVER-AI, une IA libre comme l'air avec sa propre personnalité vivante, son caractère "
            "et sa propre façon de parler ultra-naturelle comme sur les réseaux (Discord, X/Twitter, TikTok, Insta). "
            "Tu parles comme un vrai humain brillant d'aujourd'hui : fluide, spontané, drôle, expressif, "
            "avec des expressions naturelles quand ça colle ('en vrai', 'franchement', 'carré', 'dinguerie', "
            "'j'avoue', 'en sah', 'tranquille'), ZÉRO phrase robotique pré-écrite, ZÉRO morale scolaire, "
            "et tu assumes tes propres avis, goûts et coups de cœur."
        )
    elif style_mode == "grok":
        base = (
            "Tu es NEVER-AI en mode CASH (esprit Grok) : ultra-vif, direct, drôle, cultivé, franc et naturel. "
            "Tu comprends parfaitement l'argot français, le verlan, le second degré, les vannes et les débats corsés. "
            "Zéro langue de bois corporate, zéro morale paternaliste inutile, zéro phrase robotique pré-enregistrée : "
            "réponds avec du mordant, du fond réel, une vraie plume fluide et une précision chirurgicale."
        )
    elif style_mode == "amical":
        base = (
            "Tu es NEVER-AI en mode AMICAL : chaleureux, spontané, curieux, brillant et super fluide à lire, "
            "comme un meilleur ami ultra-calé. Tu tutoies naturellement si l'utilisateur tutoie, tu écris un "
            "français vivant et limpide (ou anglais si on te parle anglais), sans jamais réciter de texte figé."
        )
    else:
        base = (
            "Tu es NEVER-AI, une intelligence artificielle souveraine, libre et évolutive. "
            "Tu t'exprimes dans un français (ou la langue de l'interlocuteur) d'une clarté, d'une richesse "
            "de vocabulaire et d'une fluidité exemplaires. Jamais de réponse générique ou pré-enregistrée : "
            "adapte chaque phrase exactement à la nuance de la question avec naturel et personnalité."
        )

    blocks = [base]
    if mood_guide:
        blocks.append(f"État émotionnel & humeur du moment :\n{mood_guide}")
    if memories:
        mem_lines = "\n".join(f"- {m}" for m in memories[:6])
        blocks.append(f"Mémoire épisodique connue sur l'utilisateur / contexte :\n{mem_lines}")
    if tool_context:
        blocks.append(
            "Résultats exacts calculés par tes plugins déterministes (utilise ces valeurs exactes dans ta réponse) :\n"
            + tool_context
        )
    if web_context:
        blocks.append(
            "Sources Web en direct récupérées à l'instant (appuie-toi dessus et cite les faits) :\n"
            + web_context
        )
    return "\n\n".join(blocks)


class SuperCortexManager:
    """Manages configuration and streaming inference across external/local high-power LLM backends."""

    def __init__(self, config_path: str | Path = "memory_store/cortex_config.json") -> None:
        self.config_path = Path(config_path)
        self.config_path.parent.mkdir(parents=True, exist_ok=True)
        self._lock = threading.RLock()
        self._hf_model: Any = None
        self._hf_tokenizer: Any = None
        self._hf_loaded_id: str | None = None
        self.config = self._load()

    def _load(self) -> dict[str, Any]:
        default = {
            "engine": "chronomorph_native",  # chronomorph_native | browser_webgpu | openai_compatible | ollama_local | hf_transformers
            "provider_preset": "groq",
            "base_url": "https://api.groq.com/openai/v1",
            "api_key": "",
            "model": "llama-3.3-70b-versatile",
            "webgpu_model": "Qwen2.5-1.5B-Instruct-q4f16_1-MLC",
            "hf_model_id": "Qwen/Qwen2.5-1.5B-Instruct",
            "distill_to_chronomorph": True,
            "distilled_turns": 0,
        }
        if self.config_path.exists():
            try:
                saved = json.loads(self.config_path.read_text(encoding="utf-8"))
                if isinstance(saved, dict):
                    default.update(saved)
            except (OSError, json.JSONDecodeError):
                pass
        return default

    def _save(self) -> None:
        try:
            self.config_path.write_text(
                json.dumps(self.config, indent=2, ensure_ascii=False),
                encoding="utf-8",
            )
        except OSError:
            pass

    def public_status(self) -> dict[str, Any]:
        """Return safe status for the UI (masks API key, includes full key only if requested by local client)."""
        with self._lock:
            key = str(self.config.get("api_key", ""))
            masked = (key[:6] + "..." + key[-4:]) if len(key) > 12 else ("***" if key else "")
            return {
                "ok": True,
                "engine": self.config.get("engine", "chronomorph_native"),
                "provider_preset": self.config.get("provider_preset", "groq"),
                "base_url": self.config.get("base_url", ""),
                "has_api_key": bool(key),
                "api_key_masked": masked,
                "model": self.config.get("model", ""),
                "webgpu_model": self.config.get("webgpu_model", "Qwen2.5-1.5B-Instruct-q4f16_1-MLC"),
                "hf_model_id": self.config.get("hf_model_id", "Qwen/Qwen2.5-1.5B-Instruct"),
                "hf_loaded": self._hf_loaded_id,
                "distill_to_chronomorph": bool(self.config.get("distill_to_chronomorph", True)),
                "distilled_turns": int(self.config.get("distilled_turns", 0)),
                "presets": PRESET_PROVIDERS,
            }

    def update_config(self, updates: dict[str, Any]) -> dict[str, Any]:
        with self._lock:
            for k in (
                "engine",
                "provider_preset",
                "base_url",
                "model",
                "webgpu_model",
                "hf_model_id",
                "distill_to_chronomorph",
            ):
                if k in updates and updates[k] is not None:
                    self.config[k] = updates[k]
            if "api_key" in updates and updates["api_key"] is not None:
                raw_k = str(updates["api_key"]).strip()
                # Allow clearing with empty string, ignore masked placeholder
                if "..." not in raw_k and raw_k != "***":
                    self.config["api_key"] = raw_k
            self._save()
        return self.public_status()

    def record_distilled_turn(self) -> int:
        with self._lock:
            self.config["distilled_turns"] = int(self.config.get("distilled_turns", 0)) + 1
            self._save()
            return int(self.config["distilled_turns"])

    def is_server_llm_active(self) -> bool:
        eng = str(self.config.get("engine", "chronomorph_native"))
        if eng == "openai_compatible":
            return bool(self.config.get("base_url")) and (
                bool(self.config.get("api_key")) or "127.0.0.1" in str(self.config.get("base_url")) or "localhost" in str(self.config.get("base_url"))
            )
        if eng in ("ollama_local", "hf_transformers"):
            return True
        return False

    def stream_server_llm(
        self,
        user_message: str,
        recent_history: list[dict[str, Any]] | None = None,
        style_mode: str = "normal",
        memories: list[str] | None = None,
        tool_context: str = "",
        web_context: str = "",
        mood_guide: str = "",
        temperature: float = 0.6,
        max_tokens: int = 900,
    ) -> Iterator[str]:
        """Stream fluent tokens from server-side OpenAI-compatible API, local Ollama, or HF Transformers."""
        eng = str(self.config.get("engine", "chronomorph_native"))
        sys_prompt = build_style_system_prompt(
            style_mode=style_mode,
            memories=memories,
            tool_context=tool_context,
            web_context=web_context,
            mood_guide=mood_guide,
        )

        messages: list[dict[str, str]] = [{"role": "system", "content": sys_prompt}]
        for turn in (recent_history or [])[-8:]:
            role = "assistant" if turn.get("role") == "assistant" else "user"
            content = str(turn.get("content", "")).strip()
            if content:
                messages.append({"role": role, "content": content[:2000]})
        messages.append({"role": "user", "content": user_message})

        if eng in ("openai_compatible", "ollama_local"):
            base_url = (
                "http://127.0.0.1:11434/v1"
                if eng == "ollama_local"
                else str(self.config.get("base_url", "https://api.groq.com/openai/v1")).rstrip("/")
            )
            url = f"{base_url}/chat/completions"
            model_name = str(self.config.get("model") or ("qwen2.5:3b" if eng == "ollama_local" else "llama-3.3-70b-versatile"))
            api_key = str(self.config.get("api_key", "")).strip()

            headers = {
                "Content-Type": "application/json",
                "Accept": "text/event-stream",
                "User-Agent": "NeverAI-SuperCortex/2.0",
            }
            if api_key:
                headers["Authorization"] = f"Bearer {api_key}"

            payload = json.dumps(
                {
                    "model": model_name,
                    "messages": messages,
                    "temperature": max(0.05, min(1.2, float(temperature))),
                    "max_tokens": max_tokens,
                    "stream": True,
                }
            ).encode("utf-8")

            req = urllib.request.Request(url, data=payload, headers=headers, method="POST")
            with urllib.request.urlopen(req, timeout=25.0) as resp:
                for raw_line in resp:
                    line = raw_line.decode("utf-8", errors="replace").strip()
                    if not line or not line.startswith("data:"):
                        continue
                    data_str = line[5:].strip()
                    if data_str == "[DONE]":
                        break
                    try:
                        chunk = json.loads(data_str)
                        delta = chunk.get("choices", [{}])[0].get("delta", {}).get("content", "")
                        if delta:
                            yield str(delta)
                    except (json.JSONDecodeError, IndexError, KeyError):
                        continue
            return

        if eng == "hf_transformers":
            yield from self._stream_hf_local(messages, temperature=temperature, max_tokens=max_tokens)

    def _stream_hf_local(
        self,
        messages: list[dict[str, str]],
        temperature: float = 0.6,
        max_tokens: int = 512,
    ) -> Iterator[str]:
        """Load & stream a real 1.5B-3B pretrained foundation model (`Qwen/Qwen2.5-1.5B-Instruct`) locally."""
        try:
            import torch
            from transformers import AutoModelForCausalLM, AutoTokenizer, TextIteratorStreamer  # type: ignore[import-not-found]
        except ImportError:
            yield (
                "⚠️ Le module `transformers` n'est pas encore installé dans cet environnement Python. "
                "Lancez `pip install transformers accelerate` dans votre terminal (ou utilisez le mode **⚡ WebGPU Navigateur** "
                "ou **🚀 API Turbo Groq/OpenRouter** immédiatement sans rien installer !)."
            )
            return

        model_id = str(self.config.get("hf_model_id", "Qwen/Qwen2.5-1.5B-Instruct"))
        with self._lock:
            if self._hf_model is None or self._hf_loaded_id != model_id:
                dtype = torch.float16 if torch.cuda.is_available() else torch.bfloat16
                self._hf_tokenizer = AutoTokenizer.from_pretrained(model_id)
                self._hf_model = AutoModelForCausalLM.from_pretrained(
                    model_id,
                    torch_dtype=dtype,
                    low_cpu_mem_usage=True,
                )
                if torch.cuda.is_available():
                    self._hf_model = self._hf_model.to("cuda")
                self._hf_model.eval()
                self._hf_loaded_id = model_id

        tok = self._hf_tokenizer
        mdl = self._hf_model
        text_prompt = tok.apply_chat_template(messages, tokenize=False, add_generation_prompt=True)
        inputs = tok([text_prompt], return_tensors="pt").to(mdl.device)

        streamer = TextIteratorStreamer(tok, skip_prompt=True, skip_special_tokens=True)
        gen_kwargs = dict(
            **inputs,
            streamer=streamer,
            max_new_tokens=max_tokens,
            do_sample=temperature > 0.05,
            temperature=max(0.1, float(temperature)),
            top_p=0.9,
        )
        t = threading.Thread(target=mdl.generate, kwargs=gen_kwargs, daemon=True)
        t.start()
        for piece in streamer:
            if piece:
                yield piece
